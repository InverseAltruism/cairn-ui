// tokens.css as a pure function of src/palette.mjs.
import { rgba } from "./colour.mjs";
import { COLOURS, MODE_EXTRAS, PREFIX, SCALE, TINT_ALPHA, TINTS } from "./palette.mjs";

const decl = (name, value) => `  ${PREFIX}${name}: ${value};`;

function modeBlock(mode, indent) {
  const lines = [`color-scheme: ${mode};`];
  for (const [name, hex] of Object.entries(COLOURS[mode])) lines.push(decl(name, hex).trim());
  for (const name of TINTS) lines.push(decl(`${name}-tint`, rgba(COLOURS[mode][name], TINT_ALPHA)).trim());
  for (const [name, value] of Object.entries(MODE_EXTRAS[mode])) lines.push(decl(name, value).trim());
  return lines.map((l) => `${indent}${l}`).join("\n");
}

export function tokensCss() {
  return `/* Generated by scripts/build.mjs from src/palette.mjs: edit that file, not this one.
   Light is the default. Dark applies under a dark system setting unless the page chose light, and wherever
   data-theme="dark" is set: on <html> by theme-init.js, or on any element to make a dark island. */
:root {
${Object.entries(SCALE)
  .map(([name, value]) => decl(name, value))
  .join("\n")}
}
:root,
[data-theme="light"] {
${modeBlock("light", "  ")}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${modeBlock("dark", "    ")}
  }
}
[data-theme="dark"] {
${modeBlock("dark", "  ")}
}
`;
}
